//  NeoAlifTransliteration.swift
//  TatarKeyboardExtension
//
//  Перевод татарской кириллицы в «Neo-әlif» — активистскую латиницу 2023-24 гг.,
//  описанную на https://bababashqort.notion.site/Neo-alif-6f0934d818ba48c6946ee9ae146e5506
//  (автор — независимая доработка официального Заманалифа: те же буквы, но с
//  чёткими принципами «одна буква — одна фонема» и заменой Ää на Əə).
//
//  ПОЛНАЯ таблица соответствий букв (из документа):
//  a↔а, ə↔ә, b↔б, c↔җ, ç↔ч, d↔д, e↔е/э, f↔ф, g/ğ↔г (по гармонии), h↔һ,
//  ı↔ы, í↔«ый» (см. ниже), i↔и, j↔ж, k/q↔к (по гармонии), l↔л, m↔м, n↔н,
//  ñ↔ң, o↔о, ö↔ө, p↔п, r↔р, s↔с, ş↔ш, t↔т, u↔у, ü↔ү, v↔в (заимствования),
//  w↔в (родные слова), x↔х, y↔й, z↔з, '↔гортанная смычка в отдельных словах.
//
//  Что реализовано ниже механически (правила из документа, применимые без
//  словаря конкретных морфем):
//  1. Гармония гласных для к/г → k/q, g/ğ: если в слове есть хоть одна из
//     задних гласных (а ы о у) — «твёрдый» вариант (q, ğ) для ВСЕХ к/г в этом
//     слове; иначе — «мягкий» (k, g). Так же гармонирует ю→yu/yü и я→ya/yə.
//     Это подтверждено дословно на реальных примерах транслитерации (кычкырам
//     → qıçqıram, ләкин → ləkin, сугышып → suğışıp, менгәндә → mengəndə).
//  2. Правило «между у/ү и следующей гласной вставляется w» (из документа:
//     «When the letter U or Ü is followed by a vowel, letter W is put between
//     the vowels: алуы → aluwı»). Реализовано побуквенно.
//
//  Что НЕ реализовано (осознанное упрощение, помечено ниже подробно) —
//  описано в doc-комментарии к функции transliterate(_:).
//

import Foundation

enum NeoAlifTransliteration {

    private static let frontVowels: Set<Character> = ["ә", "е", "э", "и", "ө", "ү"]
    private static let backVowels: Set<Character> = ["а", "ы", "о", "у"]
    private static let allVowelsIncludingGlideLetters: Set<Character> =
        frontVowels.union(backVowels).union(["я", "ю", "ё"])

    private enum Harmony { case front, back }

    /// По документу гармония в пределах слова определяется наличием задних
    /// гласных где угодно в слове (не только по соседней букве) — так ведут
    /// себя все примеры в исходном документе.
    private static func harmony(of word: [Character]) -> Harmony {
        if word.contains(where: { backVowels.contains($0) }) { return .back }
        return .front
    }

    private static let directMap: [Character: String] = [
        "а": "a", "ә": "ə", "б": "b", "д": "d", "е": "e", "ё": "yo",
        "ж": "j", "җ": "c", "з": "z", "и": "i", "й": "y", "л": "l",
        "м": "m", "н": "n", "ң": "ñ", "о": "o", "ө": "ö", "п": "p",
        "р": "r", "с": "s", "т": "t", "ф": "f", "х": "x", "һ": "h",
        // ц/щ — русские заимствованные буквы, в документе не описаны;
        // берём стандартную практическую передачу.
        "ц": "ts", "ч": "ç", "ш": "ş", "щ": "şç",
        // ъ/ь обычно не несут отдельной фонемы в родных словах — опускаем.
        // (документ резервирует апостроф для гортанной смычки в отдельных
        // заимствованиях/после имён собственных — «т.е. это не то же самое»,
        // поэтому автоматически сюда апостроф не подставляем.)
        "ъ": "", "ы": "ı", "ь": "", "э": "e",
    ]

    /// Переводит одно кириллическое татарское слово (в нижнем регистре) в
    /// Neo-әlif по правилам из документа.
    ///
    /// Осознанно НЕ реализовано (нужен словарь конкретных морфем/корней,
    /// а не только буквы — иначе результат менее предсказуем, чем прямая
    /// буквенная передача):
    /// - Стяжение «ый»/«ий» → í/i перед согласной или на конце слова
    ///   (тый → tí, но тыю → tıyu) — это чередование внутри конкретных
    ///   глагольных основ, а не общее фонетическое правило.
    /// - Упрощение двойных согласных в заимствованиях (металл → metal).
    /// - Апостроф на гортанной смычке в арабизмах (Qör'ən) и после имён
    ///   собственных перед русским окончанием (Qazan'nan).
    /// - Различение в→v (заимствования) и в→w (исконные слова): здесь всегда
    ///   даёт w, как в большинстве исконно татарских слов; конкретное
    ///   заимствованное слово можно поправить вручную после генерации.
    static func transliterate(_ cyrillicWord: String) -> String {
        let word = Array(cyrillicWord.lowercased())
        let h = harmony(of: word)
        var result = ""

        for (index, ch) in word.enumerated() {
            let next: Character? = index + 1 < word.count ? word[index + 1] : nil

            switch ch {
            case "к":
                result += (h == .back) ? "q" : "k"
            case "г":
                result += (h == .back) ? "ğ" : "g"
            case "я":
                result += (h == .back) ? "ya" : "yə"
            case "ю":
                result += (h == .back) ? "yu" : "yü"
            case "в":
                result += "w"
            case "у":
                result += "u"
                if let next, allVowelsIncludingGlideLetters.contains(next) { result += "w" }
            case "ү":
                result += "ü"
                if let next, allVowelsIncludingGlideLetters.contains(next) { result += "w" }
            default:
                result += directMap[ch] ?? String(ch)
            }
        }
        return result
    }
}
