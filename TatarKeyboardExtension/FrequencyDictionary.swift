extension FrequencyDictionary {
    /// Подбирает до `limit` слов, начинающихся с `prefix`, отсортированных по
    /// частоте — используется для предиктивных подсказок при наборе (не путать
    /// со свайп-вводом в SwipeTyping.swift, у которого своя логика подбора).
    /// Для арабицы всегда возвращает пустой список — словарь пока не адаптирован
    /// под письмо без гласных букв в привычном виде (см. README).
    static func suggestions(forPrefix prefix: String, script: TatarScript, limit: Int = 3) -> [String] {
        guard script != .arabic, !prefix.isEmpty else { return [] }
        let lowered = prefix.lowercased()

        let matches: [FrequencyEntry]
        switch script {
        case .cyrillic:
            matches = entries.filter { $0.cyrillic.hasPrefix(lowered) }
        case .latin:
            matches = entries.filter { $0.latin.hasPrefix(lowered) }
        case .arabic:
            matches = []
        }

        return matches
            .sorted { $0.frequency > $1.frequency }
            .prefix(limit)
            .map { script == .cyrillic ? $0.cyrillic : $0.latin }
    }
}
